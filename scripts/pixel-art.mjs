#!/usr/bin/env node
// Turns a pixel-art PNG into a sprite module the home can draw: a grid of single-character cells plus the color
// for each character. The PNG can be exported at any whole-number scale; the cell size is found from where the
// colors change. Transparent edges are trimmed.
//
//   node scripts/pixel-art.mjs assets/home/items/sofa.png            → src/features/home/art/sprites/sofa.ts
//   node scripts/pixel-art.mjs assets/home/items/sofa.png --cell 25  (if the cell size is guessed wrong)

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { basename, dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import pngjs from 'pngjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(root, 'src/features/home/art/sprites');
// Characters for colors, most-used first. '.' is reserved for transparent.
const LETTERS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';

const args = process.argv.slice(2);
const file = args.find((a) => !a.startsWith('--') && !/^\d+$/.test(a));
const cellArg = args.includes('--cell') ? Number(args[args.indexOf('--cell') + 1]) : undefined;
if (!file) {
  console.error('Usage: node scripts/pixel-art.mjs <file.png> [--cell N]');
  process.exit(1);
}

const png = pngjs.PNG.sync.read(readFileSync(file));
const { width, height, data } = png;
const at = (x, y) => {
  const i = (y * width + x) * 4;
  // Anything mostly transparent counts as transparent; anything else as fully opaque.
  if (data[i + 3] < 128) return null;
  return '#' + [data[i], data[i + 1], data[i + 2]].map((v) => v.toString(16).padStart(2, '0')).join('');
};

const gcd = (a, b) => (b ? gcd(b, a % b) : a);
let cell = cellArg;
if (!cell) {
  cell = gcd(width, height);
  for (let y = 0; y < height && cell > 1; y++) for (let x = 1; x < width; x++) if (at(x, y) !== at(x - 1, y)) cell = gcd(cell, x);
  for (let x = 0; x < width && cell > 1; x++) for (let y = 1; y < height; y++) if (at(x, y) !== at(x, y - 1)) cell = gcd(cell, y);
}
if (width % cell || height % cell) {
  console.error(`The image (${width}×${height}) doesn't divide into ${cell}px cells.`);
  process.exit(1);
}

// Sample each cell, and check it's one solid color (a smoothed export would not be).
const cols = width / cell;
const rowsN = height / cell;
const grid = [];
let mixed = 0;
for (let r = 0; r < rowsN; r++) {
  const row = [];
  for (let c = 0; c < cols; c++) {
    const color = at(c * cell, r * cell);
    for (let y = r * cell; y < (r + 1) * cell; y++)
      for (let x = c * cell; x < (c + 1) * cell; x++) if (at(x, y) !== color) { mixed++; y = Infinity; break; }
    row.push(color);
  }
  grid.push(row);
}
if (mixed) console.warn(`Warning: ${mixed} cells aren't a single color. Was the export smoothed? Use nearest-neighbour scaling.`);

// Trim the transparent margin.
const filled = (cells) => cells.some((c) => c !== null);
let top = 0, bottom = rowsN - 1, left = 0, right = cols - 1;
while (top < bottom && !filled(grid[top])) top++;
while (bottom > top && !filled(grid[bottom])) bottom--;
while (left < right && !filled(grid.map((row) => row[left]))) left++;
while (right > left && !filled(grid.map((row) => row[right]))) right--;
const trimmed = grid.slice(top, bottom + 1).map((row) => row.slice(left, right + 1));

const counts = new Map();
for (const row of trimmed) for (const c of row) if (c) counts.set(c, (counts.get(c) ?? 0) + 1);
if (counts.size > LETTERS.length) {
  console.error(`Too many colors (${counts.size}); the most a sprite can have is ${LETTERS.length}.`);
  process.exit(1);
}
const letterOf = new Map([...counts].sort((a, b) => b[1] - a[1]).map(([color], i) => [color, LETTERS[i]]));

const name = basename(file, '.png');
const ident = name.replace(/-(\w)/g, (_, ch) => ch.toUpperCase());
const rows = trimmed.map((row) => row.map((c) => (c ? letterOf.get(c) : '.')).join(''));
const paint = [...letterOf].map(([color, letter]) => `${letter}: '${color}'`).join(', ');

const source = `// Generated by scripts/pixel-art.mjs from ${relative(root, file)}. Don't edit by hand: change the PNG and run it again.
import type { Sprite } from '@/design-system/icons/PixelArt';

export const ${ident}: Sprite = {
  rows: [
${rows.map((r) => `    '${r}',`).join('\n')}
  ],
  paint: { ${paint} },
};
`;

mkdirSync(OUT_DIR, { recursive: true });
const out = join(OUT_DIR, `${name}.ts`);
writeFileSync(out, source);
console.log(`${relative(root, out)}: ${rows[0].length}×${rows.length} cells (${cell}px each in the PNG), ${counts.size} colors.`);
